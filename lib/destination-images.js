export function getDestinationImage(destination) {
  // Direct match
  if (destinationImages[destination]) {
    return destinationImages[destination];
  }
  
  // Try partial match
  const key = Object.keys(destinationImages).find(k => 
    destination.toLowerCase().includes(k.toLowerCase()) ||
    k.toLowerCase().includes(destination.toLowerCase())
  );
  
  if (key) {
    return destinationImages[key];
  }
  
  // Fallback - beautiful generic travel image
  return 'https://images.unsplash.com/photo-1488646953014-85cb44e25828?w=1200&q=80';
}
